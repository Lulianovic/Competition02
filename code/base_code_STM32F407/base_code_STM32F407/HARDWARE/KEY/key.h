/**
 ******************************************************************************
 * @file    key.h
 * @brief   按键输入驱动头文件
 *
 * 定义按键硬件接口、电平逻辑及扫描函数。
 * 默认使用 PB0 作为独立按键输入引脚，配置为 **下拉输入**：
 * - 按键未按下：PB0 = 低电平（0）
 * - 按键按下：PB0 = 高电平（1）
 *
 * @note    - 按键电路需将 PB0 通过上拉（或直接）连接至 VCC，另一端接地
 *          - Key_Scan() 函数支持任意 GPIO 引脚，便于扩展多按键
 *          - 电平定义通过 KEY_ON / KEY_OFF 统一管理，便于移植
 ******************************************************************************
 */
#ifndef __KEY_H
#define __KEY_H	 
 
#include "stm32f4xx.h"
#include "stm32f4xx_conf.h"

/**
 * @defgroup KEY_GPIO_Macros 按键默认引脚宏定义
 * @{
 * @brief  默认按键连接到 PB0
 *
 * 使用 \c PBin(0) 直接读取引脚电平（需 \c sys.h 支持）。
 * 若更改硬件引脚，应同步修改此宏及 \ref KEY_Init() 中的初始化代码。
 */
#define KEY PBin(0)
	 
/**
 * @brief  初始化默认按键引脚（PB0）为下拉输入模式
 *
 * 配置 GPIOB.0 为下拉输入（GPIO_Mode_IPD），确保无按键时为低电平。
 *
 * @note   若使用其他引脚或上拉模式，需修改此函数实现。
 */
void KEY_Init(void);

			    
#endif  /* __KEY_H */
